"""File scanning with the guards from spec section 4."""
from __future__ import annotations
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable
from . import config


class Cancelled(Exception):
    pass


@dataclass
class ScanResult:
    py_files: list[str] = field(default_factory=list)       # repo-relative posix paths
    other_files: list[str] = field(default_factory=list)    # non-Python files, kept for roles / file lists
    context_files: list[str] = field(default_factory=list)
    skipped: int = 0
    truncated: bool = False  # hit MAX_FILES


def _looks_generated(path: Path) -> bool:
    name = path.name.lower()
    if name.endswith((".min.js", ".min.css", "_pb2.py", "_pb2_grpc.py")):
        return True
    try:
        with open(path, "rb") as f:
            head = f.read(400).lower()
    except OSError:
        return True
    return b"generated by" in head or b"do not edit" in head or b"auto-generated" in head


def _is_minified(path: Path) -> bool:
    try:
        with open(path, "rb") as f:
            chunk = f.read(4000)
    except OSError:
        return True
    return len(chunk) > 3000 and chunk.count(b"\n") < 3


def scan(root: Path, check_cancel: Callable[[], None] = lambda: None) -> ScanResult:
    res = ScanResult()
    total = 0
    for dirpath, dirnames, filenames in os.walk(root):
        check_cancel()
        dirnames[:] = sorted(d for d in dirnames if d not in config.IGNORED_DIRS)
        for fn in sorted(filenames):
            full = Path(dirpath) / fn
            rel = full.relative_to(root).as_posix()
            if full.is_symlink():
                continue
            try:
                size = full.stat().st_size
            except OSError:
                continue
            is_py = fn.endswith(".py")
            lower = fn.lower()
            is_ctx = lower in config.CONTEXT_FILE_NAMES or lower.endswith((".tf", ".tfvars")) or "dockerfile" in lower
            if is_ctx:
                res.context_files.append(rel)
            if size > config.MAX_FILE_BYTES:
                res.skipped += 1
                continue
            if is_py:
                if _looks_generated(full) or _is_minified(full):
                    res.skipped += 1
                    continue
                total += 1
                if total > config.MAX_FILES:
                    res.truncated = True
                    return res
                res.py_files.append(rel)
            else:
                res.other_files.append(rel)
    return res
